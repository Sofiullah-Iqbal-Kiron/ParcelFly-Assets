"""Rebuild the whole Parcel Fly brand kit from source.

    .venv/bin/python source/build/build_all.py [--motion-force]

Order matters: the guidelines embed files produced by the earlier steps.
The wordmark master (source/master/wordmark-en.svg) is only regenerated by extract_wordmark.py, which needs a
locally licensed copy of Nasalization Rg; it is not part of this build.
"""
import subprocess
import sys
import time
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
sys.path.insert(0, str(HERE))
SKILL = ROOT / ".claude" / "skills" / "logo-design" / "scripts"

EM_DASH = chr(0x2014)
STEPS = ["build_logos", "build_icons", "build_maps", "build_social", "build_marks", "build_print", "build_system",
         "build_motion", "build_bags", "build_merch", "build_mockups", "build_web", "build_wallpapers", "build_guidelines"]


def run(cmd):
    t = time.time()
    r = subprocess.run(cmd, cwd=ROOT, capture_output=True, text=True)
    if r.returncode != 0:
        print(r.stdout, r.stderr)
        raise SystemExit(f"failed: {' '.join(map(str, cmd))}")
    print(f"  {r.stdout.strip().splitlines()[-1] if r.stdout.strip() else 'ok'}  ({time.time() - t:.1f}s)")


def no_em_dash(paths):
    """House rule: no em dash anywhere in delivered files (the skill's HTML templates add some)."""
    for p in paths:
        s = p.read_text(encoding="utf-8")
        if EM_DASH in s:
            p.write_text(s.replace(f" {EM_DASH} ", " · ").replace(EM_DASH, "-"), encoding="utf-8")


def main():
    py = sys.executable
    for step in STEPS:
        print(step)
        extra = []
        if step == "build_motion" and "--motion-force" not in sys.argv:
            extra = ["--skip-existing"]   # videos are slow: only render what is missing (use --motion-force after edits)
        run([py, str(HERE / f"{step}.py"), *extra])
    print("presentation (logo-design skill)")
    (ROOT / "presentation").mkdir(exist_ok=True)
    run([py, str(SKILL / "presentation_board.py"), "source/presentation/presentation-spec.json", "-o",
         "presentation/parcelfly-brand-board.html"])
    run([py, str(SKILL / "preview_sheet.py"), "logo/symbol/parcelfly-symbol-color.svg",
         "logo/horizontal/parcelfly-horizontal-color.svg", "logo/primary-stacked/parcelfly-stacked-color.svg",
         "icons/app/parcelfly/web/favicon.svg", "--names", "Symbol", "Horizontal", "Stacked", "Favicon crop",
         "--name", "Parcel Fly", "--brand-color", "#000080", "--refs-industry", "travel-transport",
         "-o", "presentation/parcelfly-test-sheet.html"])
    no_em_dash(list((ROOT / "presentation").glob("*.html")))
    print("audit (logo-design skill)")
    r = subprocess.run([py, str(SKILL / "svg_audit.py"), "logo/symbol/parcelfly-symbol-color.svg",
                        "logo/primary-stacked/parcelfly-stacked-color.svg", "logo/horizontal/parcelfly-horizontal-color.svg"],
                       cwd=ROOT, capture_output=True, text=True)
    (ROOT / "presentation" / "svg-audit.txt").write_text(r.stdout, encoding="utf-8")
    print("overview")
    run([py, str(HERE / "build_overview.py")])
    n = sum(1 for p in ROOT.rglob("*") if p.is_file() and ".venv" not in p.parts and ".claude" not in p.parts
            and "source" not in p.parts)
    print(f"done: {n} delivered files")


if __name__ == "__main__":
    main()
